# Peça um número e mostre seu dobro, triplo e raiz quadrada.
numero = int(input('Digite um numero: '))
dobro = numero * 2
triplo = numero * 3
raiz_quadrada = numero ** (1/2)

print(f'Dobro de {numero} = {dobro}')
print(f'Triplo de {numero} = {triplo}')
print(f'Raiz quadrada de {numero} = {raiz_quadrada}')